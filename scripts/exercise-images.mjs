// Downloads the built-in exercise pictures and writes the map the app uses.
//
// The pictures come from RepDB's free exercise dataset
// (https://github.com/sergei-argutin/exercise-dataset). Their licence allows
// use inside an app with the credit "Exercise data by RepDB (repdb.co)"
// (shown in Profile), but not republishing them. This repository is public,
// so the .webp files are gitignored and fetched here instead; npm runs this
// script after every install.
//
// assets/exercises/sources.json maps our exercise slug to the RepDB id.
// Usage: node scripts/exercise-images.mjs

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = join(root, 'assets', 'exercises');
const mapFile = join(root, 'src', 'features', 'exercises', 'exerciseImages.ts');
const BASE = 'https://raw.githubusercontent.com/sergei-argutin/exercise-dataset/main/images/flat';
// The mid-movement pose shows an exercise best; holds only have one pose.
const POSES = ['peak', 'start', 'main'];

const sources = JSON.parse(readFileSync(join(imagesDir, 'sources.json'), 'utf8'));
const slugs = Object.keys(sources).sort();

async function download(slug, repdbId) {
  for (const pose of POSES) {
    const response = await fetch(`${BASE}/${repdbId}-${pose}.webp`);
    if (response.ok) {
      writeFileSync(join(imagesDir, `${slug}.webp`), Buffer.from(await response.arrayBuffer()));
      return true;
    }
  }
  return false;
}

let downloaded = 0;
const failed = [];
for (const slug of slugs) {
  if (existsSync(join(imagesDir, `${slug}.webp`))) continue;
  try {
    if (await download(slug, sources[slug])) downloaded++;
    else failed.push(slug);
  } catch {
    failed.push(slug);
  }
}

// Metro needs every require() written out, so generate them. Relative
// paths work for both Metro and Jest.
const lines = slugs.map((slug) => `  ${slug}: require('../../../assets/exercises/${slug}.webp'),`);
writeFileSync(
  mapFile,
  `// Generated by scripts/exercise-images.mjs from assets/exercises/sources.json.
// Don't edit by hand: change sources.json and run the script again.
import type { ImageSourcePropType } from 'react-native';

export const EXERCISE_IMAGES: Partial<Record<string, ImageSourcePropType>> = {
${lines.join('\n')}
};
`,
);

console.log(`Exercise images: ${downloaded} downloaded, ${slugs.length - downloaded - failed.length} already there.`);
// Never fail the install (e.g. no signal); the bundler will point at any
// missing file, and running this script again fills the gaps.
if (failed.length > 0) console.warn(`Could not download: ${failed.join(', ')}`);
